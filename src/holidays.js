export function mergeHolidayText(text, dates) {
  const set = new Set(
    String(text || "")
      .split(/[\s,]+/)
      .map((v) => v.trim())
      .filter(Boolean)
  );
  (dates || []).forEach((d) => set.add(d));
  return [...set].sort().join("\n");
}
